def K(testo: str, pic: int) -> str:
    """VALUE di un PIC X(pic): riempie di spazi a destra, errore se il testo non entra."""
    if len(testo) > pic:
        raise ValueError(f"{testo!r}: {len(testo)} caratteri, PIC X({pic})")
    return testo.ljust(pic)


